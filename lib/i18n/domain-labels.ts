/**
 * Photo captions generated by scripts/generate-db.js follow a fixed
 * "{PartLabel} — зафиксированные повреждения" pattern. Reconstructs it in
 * the target locale via reverse lookup; falls back to the raw caption for
 * anything that doesn't match (e.g. a hand-written admin caption).
 */
export function translatePhotoCaption(caption: string, dict: Dictionary): string {
  const match = caption.match(/^(.+?) — зафиксированные повреждения$/u);
  if (!match) return caption;
  const ruLabel = match[1];
  const part = ruLabel ? RU_LABEL_TO_PART[ruLabel] : undefined;
  if (!part) return caption;
  return `${dict.damagedParts[part]} ${dict.timeline.photoCaptionSuffix}`;
}

/**
 * Rebuilds a "{city}, ул. {street}, {number}" style address (as emitted by
 * scripts/generate-db.js) in the target locale. City and street names are
 * translated via the known-value maps; falls back to the raw string
 * unchanged if it doesn't match the expected generator format (e.g. a
 * custom address an admin typed by hand).
 */
export function translateAddress(address: string, dict: Dictionary): string {
  const match = address.match(/^(.+?),\s*ул\.\s*(.+?),\s*(\d+)$/u);
  if (!match) return address;
  const [, city, street, number] = match;
  if (!city || !street || !number) return address;

  const translatedCity = translateCity(city, dict);
  const translatedStreet = translateStreet(street, dict);
  const streetAbbr = dict.common.streetAbbr;

  // Uzbek convention places the designator after the name ("... ko'chasi"),
  // Russian/English place it before ("ул. ..." / "... St.").
  const streetLabel =
    streetAbbr === "ko'chasi" ? `${translatedStreet} ${streetAbbr}` : `${streetAbbr} ${translatedStreet}`;

  return `${translatedCity}, ${streetLabel}, ${number}`;
}
